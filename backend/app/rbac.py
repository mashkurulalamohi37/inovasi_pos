def role_has_permission(role_code: str, permission_code: str, overrides: dict[str, bool] | None = None) -> bool:
    key = f"{role_code}:{permission_code}"
    if overrides and key in overrides:
        return overrides[key]
    if role_code and role_code.lower() in ("admin", "super admin", "super_admin", "platform_admin"):
        return True
    return permission_code in DEFAULT_ROLE_PERMISSIONS.get(role_code, set())
