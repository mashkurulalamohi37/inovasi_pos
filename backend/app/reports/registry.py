def list_catalog(advanced_enabled: bool = True) -> list[dict[str, Any]]:
    out: list[dict[str, Any]] = []
    for item in REPORT_CATALOG.values():
        if item["advanced"] and not advanced_enabled:
            continue
        out.append({
            "key": item["key"],
            "name": item["name"],
            "description": item["description"],
            "permission": item["permission"],
            "advanced": item["advanced"],
            "priority": item.get("priority", "legacy"),
            "filters": item.get("filters", []),
            "formats": item.get("formats", _EXPORT_FORMATS),
            "format_notes": item.get("format_notes", {}),
            "drill_down": item.get("drill_down"),
            "columns": item.get("columns"),
            "totals": item.get("totals"),
            "required_filters": item.get("required_filters"),
            "group_by": item.get("group_by"),
        })
    return sorted(out, key=lambda x: (0 if x["priority"] == "P0" else 1 if x["priority"] == "P1" else 2, x["name"]))


def get_report_def(report_key: str) -> dict[str, Any] | None:
    if not report_key:
        return None
    normalized = report_key.replace("_", "-")
    return REPORT_CATALOG.get(report_key) or REPORT_CATALOG.get(normalized)
