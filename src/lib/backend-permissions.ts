export function backendHasPermission(backendPerms: string[], perm: Permission): boolean {
  if (backendPerms.includes("*") || backendPerms.includes("admin")) return true;
  const codes = FRONTEND_TO_BACKEND[perm];
  if (!codes) return backendPerms.some(p => p.startsWith(perm.split(".")[0]));
  return codes.some(c => backendPerms.includes(c));
}
